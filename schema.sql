CREATE TABLE profiles (
    id uuid references auth.users not null primary key,
    name text,
    is_artisan boolean default false,
    contact text,
    city text,
    bio text,
    created_at timestamptz default now()
);

CREATE TABLE products (
    id bigint generated by default as identity primary key,
    artisan_id uuid references profiles(id) on delete cascade not null,
    title text not null,
    description text,
    price numeric not null check (price >= 0),
    image_url text,
    category text,
    created_at timestamptz default now()
);

CREATE TABLE sales (
    id bigint generated by default as identity primary key,
    product_id bigint references products(id) on delete set null,
    buyer_id uuid references profiles(id) on delete set null,
    created_at timestamptz default now()
);

alter table profiles enable row level security;
alter table products enable row level security;
alter table sales enable row level security;

create policy "Public profiles are viewable by everyone." on profiles for select using (true);
create policy "Users can insert their own profile." on profiles for insert with check (auth.uid() = id);
create policy "Users can update own profile." on profiles for update using (auth.uid() = id);

create policy "Products are viewable by everyone." on products for select using (true);
create policy "Artisans can insert products" on products for insert with check (auth.uid() = artisan_id);
create policy "Artisans can update own products" on products for update using (auth.uid() = artisan_id);
create policy "Artisans can delete own products" on products for delete using (auth.uid() = artisan_id);

create policy "Sales viewable by artisan or buyer" on sales for select using (
    auth.uid() = buyer_id OR auth.uid() IN (SELECT artisan_id FROM products WHERE id = product_id)
);
create policy "Buyers can insert sales" on sales for insert with check (auth.uid() = buyer_id);

create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, name, is_artisan, contact, city)
  values (
    new.id,
    new.raw_user_meta_data->>'name',
    (new.raw_user_meta_data->>'is_artisan')::boolean,
    new.raw_user_meta_data->>'contact',
    new.raw_user_meta_data->>'city'
  );
  return new;
end;
$$ language plpgsql security definer;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();